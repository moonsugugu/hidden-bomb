// 같은 개념을 여러 상황에서 반복해서 연습할 수 있도록 기본 문항마다
// 중립적인 생각 도움말을 붙인 변형을 함께 제공한다. 도움말은 정답을
// 알려 주지 않으므로 참·거짓 판정과 설명은 원문 그대로 유지된다.
export const BANK_VARIANTS = 10;
const VARIANT_CONTEXTS = [
  "",
  "다시 한 번 생각해 보세요",
  "친구에게 설명해 보세요",
  "소리 내어 읽어 보세요",
  "공책에 써 보세요",
  "생활 속 예를 찾아 보세요",
  "짝과 함께 확인해 보세요",
  "오늘 배운 내용을 떠올려 보세요",
  "한 번 더 살펴보세요",
  "우리 반 친구와 이야기해 보세요",
];

function addVariantContext(text, context) {
  if (!context) return text;
  const base = String(text).replace(/[.!?。！？]+$/u, "");
  return `${base}. (${context})`;
}

function expandSpellingPool(entries) {
  return entries.flatMap(([correct, wrong, point]) =>
    VARIANT_CONTEXTS.map((context) => [
      addVariantContext(correct, context),
      addVariantContext(wrong, context),
      point,
    ]),
  );
}

function expandPropositionPool(entries) {
  return entries.flatMap(([text, isTrue, explain]) =>
    VARIANT_CONTEXTS.map((context) => [addVariantContext(text, context), isTrue, explain]),
  );
}

// 기본 문항은 검토된 원문을 유지하고, 각 학년·과목 세트만 동일한 방식으로 확장한다.
for (const gradeBand of Object.keys(SPELLING))
  SPELLING[gradeBand] = expandSpellingPool(SPELLING[gradeBand]);
for (const subject of Object.keys(PROPOSITIONS))
  for (const gradeBand of Object.keys(PROPOSITIONS[subject]))
    PROPOSITIONS[subject][gradeBand] = expandPropositionPool(PROPOSITIONS[subject][gradeBand]);

/** 문제은행 카드의 형식·중복·참거짓 표시를 독립적으로 점검한다. */
export function validateQuestionBank() {
  const errors = [];
  const checkSpelling = (items, label) => {
    const seen = new Set();
    for (const [index, item] of items.entries()) {
      const [correct, wrong, point] = item;
      if (!correct || typeof correct !== "string") errors.push(`${label}[${index}] 정답 문장이 비어 있어요.`);
      if (!wrong || typeof wrong !== "string") errors.push(`${label}[${index}] 폭탄 문장이 비어 있어요.`);
      if (correct === wrong) errors.push(`${label}[${index}] 정답과 폭탄 문장이 같아요.`);
      if (!point || typeof point !== "string") errors.push(`${label}[${index}] 맞춤법 해설이 비어 있어요.`);
      for (const text of [correct, wrong]) {
        if (seen.has(text)) errors.push(`${label}[${index}] 문장이 중복돼요: ${text}`);
        seen.add(text);
      }
    }
  };
  const checkProposition = (items, label) => {
    const seen = new Set();
    for (const [index, item] of items.entries()) {
      const [text, isTrue, explain] = item;
      if (!text || typeof text !== "string") errors.push(`${label}[${index}] 문장이 비어 있어요.`);
      if (typeof isTrue !== "boolean") errors.push(`${label}[${index}] 참·거짓 표시가 없어요.`);
      if (!explain || typeof explain !== "string") errors.push(`${label}[${index}] 해설이 비어 있어요.`);
      if (seen.has(text)) errors.push(`${label}[${index}] 문장이 중복돼요: ${text}`);
      seen.add(text);
    }
  };

  for (const [gradeBand, items] of Object.entries(SPELLING))
    checkSpelling(items, `spelling/${gradeBand}`);
  for (const [subject, bands] of Object.entries(PROPOSITIONS))
    for (const [gradeBand, items] of Object.entries(bands))
      checkProposition(items, `proposition/${subject}/${gradeBand}`);
  return errors;
}

const shuffle = (items, rng) => {
  const copy = [...items];
  for (let index = copy.length - 1; index > 0; index -= 1) {
    const swap = Math.floor(rng() * (index + 1));
    [copy[index], copy[swap]] = [copy[swap], copy[index]];
  }
  return copy;
};

const makeCard = (text, isTrue, explain, tag) => ({
  id: randomUUID().slice(0, 8),
  text,
  isTrue,
  explain,
  tag,
});

/**
 * 그 설정으로 실제 몇 장짜리 덱을 만들 수 있는지 돌려준다.
 *
 * 명제는 참·거짓이 문장에 고정되어 있어 원시 문항 수가 곧 덱 크기가 아니다.
 * 폭탄 비율을 지키려면 한쪽이 모자란 만큼 덱이 줄어들므로 그 값을 그대로 계산한다.
 * 맞춤법은 한 항목에서 양쪽 문장을 다 만들 수 있어 원시 개수가 곧 덱 크기다.
 */
export function poolSize({ questionType, gradeBand, subject, bombRatio = 0.3 }) {
  if (questionType === "spelling") return (SPELLING[gradeBand] || []).length;
  if (questionType !== "proposition") return 0;

  const pool = PROPOSITIONS[subject]?.[gradeBand] || [];
  const trueCount = pool.filter(([, isTrue]) => isTrue).length;
  const falseCount = pool.length - trueCount;
  const ratio = Math.min(0.99, Math.max(0.01, bombRatio));
  return Math.min(
    Math.floor(trueCount / (1 - ratio)),
    Math.floor(falseCount / ratio),
  );
}

/**
 * 맞춤법 덱을 만든다.
 * 한 항목에서 정답 문장과 폭탄 문장을 모두 만들 수 있으므로
 * 폭탄 개수를 정확히 맞출 수 있다.
 */
export function generateSpelling({
  gradeBand = "g34",
  count = 40,
  bombCount = 12,
  rng = Math.random,
} = {}) {
  const pool = SPELLING[gradeBand] || SPELLING.g34;
  const total = Math.min(count, pool.length);
  const bombs = Math.min(bombCount, total);
  const picked = shuffle(pool, rng).slice(0, total);
  const items = picked.map(([correct, wrong, point], index) =>
    index < bombs
      ? makeCard(wrong, false, `'${point}'가 틀렸어요. 바른 문장은 "${correct}" 입니다.`, `spelling:${point}`)
      : makeCard(correct, true, `'${point}'를 바르게 썼어요.`, `spelling:${point}`),
  );
  return shuffle(items, rng);
}

/**
 * 명제 덱을 만든다.
 *
 * 맞춤법과 달리 참·거짓이 문장에 고정되어 있어, 한쪽이 모자라면 덱을 다 채울 수 없다.
 * 이때 그냥 있는 대로 담으면 폭탄 비율이 30%가 아니라 50%까지 치솟아 게임이 훨씬 어려워진다.
 * 그래서 **비율을 먼저 지키고 덱 크기를 줄인다.** 짧은 게임이 불공정한 게임보다 낫다.
 */
export function generateProposition({
  gradeBand = "g34",
  subject = "math",
  count = 40,
  bombCount = 12,
  rng = Math.random,
} = {}) {
  const pool = PROPOSITIONS[subject]?.[gradeBand] || PROPOSITIONS.math.g34;
  const cards = pool.map(([text, isTrue, explain]) =>
    makeCard(text, isTrue, explain, `${subject}:${gradeBand}`),
  );
  const bombPool = shuffle(cards.filter((item) => !item.isTrue), rng);
  const safePool = shuffle(cards.filter((item) => item.isTrue), rng);

  const ratio = count > 0 ? Math.min(1, Math.max(0, bombCount / count)) : 0;
  if (ratio <= 0) return shuffle(safePool.slice(0, count), rng);
  if (ratio >= 1) return shuffle(bombPool.slice(0, count), rng);

  // 참·거짓 각각이 감당할 수 있는 최대 덱 크기를 구해 그중 작은 쪽을 따른다.
  const total = Math.min(
    count,
    Math.floor(safePool.length / (1 - ratio)),
    Math.floor(bombPool.length / ratio),
  );
  const bombs = Math.min(Math.round(total * ratio), bombPool.length);
  const safes = Math.min(total - bombs, safePool.length);
  return shuffle([...bombPool.slice(0, bombs), ...safePool.slice(0, safes)], rng);
}

export const BANK_STATS = Object.freeze({
  spelling: Object.fromEntries(
    Object.entries(SPELLING).map(([band, items]) => [band, items.length]),
  ),
  proposition: Object.fromEntries(
    Object.entries(PROPOSITIONS).map(([subject, bands]) => [
      subject,
      Object.fromEntries(Object.entries(bands).map(([band, items]) => [band, items.length])),
    ]),
  ),
});
